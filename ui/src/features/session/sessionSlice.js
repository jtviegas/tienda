import { createAsyncThunk, createSlice } from '@reduxjs/toolkit';
import { signUp, confirmSignUp, login, forgotPswd, confirmForgotPswd } from './auth';

const initialState = {
  value: null,
  status: 'idle',
  error: null
};

// The function below is called a thunk and allows us to perform async logic. It
// can be dispatched like a regular action: `dispatch(incrementAsync(10))`. This
// will call the thunk with the `dispatch` function as the first argument. Async
// code can then be executed and other actions can be dispatched. Thunks are
// typically used to make async requests.
export const signupAsync = createAsyncThunk('session/signup', signUp);
export const confirmSignUpAsync = createAsyncThunk('session/confirmSignUp', confirmSignUp);
export const loginAsync = createAsyncThunk('session/login', login);
export const forgotPswdAsync = createAsyncThunk('session/forgotPswd', forgotPswd);
export const confirmForgotPswdAsync = createAsyncThunk('session/confirmForgotPswd', confirmForgotPswd);

export const sessionSlice = createSlice({
  name: 'session',
  initialState,

  // The `extraReducers` field lets the slice handle actions defined elsewhere,
  // including actions generated by createAsyncThunk or in other slices.
  extraReducers: (builder) => {
    builder
    .addCase(loginAsync.pending, (state) => {
      state.status = 'loading';
      state.error = null;
      state.value = null;
    })
    .addCase(loginAsync.fulfilled, (state, action) => {
      state.status = 'idle';
      state.error = null;
      state.value = {"confirmed": action.payload.UserConfirmed};
    })
    .addCase(loginAsync.rejected, (state, action) => {
      state.status = 'failed';
      state.error = action.error.message ?? 'Unknown Error';
      state.value = null;
    })
      .addCase(signupAsync.pending, (state) => {
        state.status = 'loading';
        state.error = null;
        state.value = null;
      })
      .addCase(signupAsync.fulfilled, (state, action) => {
        state.status = 'idle';
        state.error = null;
        state.value = {"confirmed": action.payload.UserConfirmed, "email": action.meta.arg.email};
      })
      .addCase(signupAsync.rejected, (state, action) => {
        state.status = 'failed';
        state.error = action.error.message ?? 'Unknown Error';
        state.value = null;
      })
      .addCase(confirmSignUpAsync.pending, (state) => {
        state.status = 'loading';
        state.error = null;
      })
      .addCase(confirmSignUpAsync.fulfilled, (state, action) => {
        console.log("confirmSignUpAsync.fulfilled")
        state.status = 'idle';
        state.error = null;
        state.value = {...state.value, "confirmed": true};
      })
      .addCase(confirmSignUpAsync.rejected, (state, action) => {
        state.status = 'failed'
        state.error = action.error.message ?? 'Unknown Error'
      })
      ;
  },
});


export const selectSessionValue = (state) => state.session.value;
export const selectSessionStatus = (state) => state.session.status;
export const selectSessionError = (state) => state.session.error;


export default sessionSlice.reducer;
